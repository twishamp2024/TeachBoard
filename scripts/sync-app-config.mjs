// Copies identity fields from app.config.json (the single source of truth for
// the application name and version) into package.json, which electron-builder
// and npm read.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const app = JSON.parse(readFileSync(join(root, 'app.config.json'), 'utf8'))
const pkgPath = join(root, 'package.json')
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))

if (!app.appName || app.appName === 'Your App Name') {
  console.error('app.config.json: set "appName" before packaging.')
  process.exit(1)
}

const next = { ...pkg, productName: app.appName, version: app.version, description: app.description, author: app.author }
if (JSON.stringify(next) !== JSON.stringify(pkg)) {
  writeFileSync(pkgPath, JSON.stringify(next, null, 2) + '\n')
  console.log(`package.json synced: ${app.appName} ${app.version}`)
} else {
  console.log(`package.json already matches ${app.appName} ${app.version}`)
}

// NSIS uninstall hook: remove the file-extension key the association leaves
// behind, but only while it still points at this app's file type.
const nsh = `; Generated by scripts/sync-app-config.mjs from app.config.json — do not edit.
!macro customUnInstall
  ReadRegStr $0 SHCTX "Software\\Classes\\.${app.fileExtension}" ""
  \${If} $0 == "${app.fileDescription}"
    DeleteRegKey SHCTX "Software\\Classes\\.${app.fileExtension}"
    System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'
  \${EndIf}
!macroend
`
writeFileSync(join(root, 'build', 'installer.nsh'), nsh)
console.log('build/installer.nsh written')
